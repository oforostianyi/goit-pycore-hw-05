"""Модуль для розбору введеного користувачем рядка на команду та аргументи."""


def parse_input(user_input: str) -> tuple[str, ...]:
    """
    Розбирає введений рядок на команду та її аргументи.

    Команда приводиться до нижнього регістру, тож програма не чутлива
    до того, як саме користувач написав її ("HELLO", "Hello", "hello"
    обробляються однаково). Аргументи зберігають оригінальний регістр,
    бо імена контактів важливі такими, якими їх ввів користувач.

    Якщо рядок порожній або складається лише з пробілів, повертається
    кортеж із порожньою командою — головний цикл сприйме це як невірну
    команду.

    :param user_input: рядок, введений користувачем
    :return: кортеж (команда, *аргументи)
    """
    if not user_input.strip():
        return ("",)

    cmd, *args = user_input.split()
    cmd = cmd.strip().lower()
    return cmd, *args