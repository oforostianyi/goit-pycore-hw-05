def caching_fibonacci():
    """
    Створює та повертає внутрішню функцію fibonacci(n), 
    яка обчислює n-е число Фібоначчі з використанням кешу.
    Це ілюстрація використання замикання (closure) для збереження стану.
    """
    # 1. Створюємо словник cache, який зберігатиме всі обчислені значення.
    cache = {}

    # Ініціалізуємо базові випадки в кеші
    cache[0] = 0
    cache[1] = 1

    def fibonacci(n):
        """
        Внутрішня функція, яка обчислює F(n) рекурсивно з кешуванням.
        Вона "запам'ятовує" змінну 'cache' зі свого лексичного контексту (завдяки замиканню).
        """
        # Перевірка на коректність вхідних даних
        if not isinstance(n, int) or n < 0:
            raise ValueError("Введене число має бути невід’ємним цілим.")

        # Крок 1: Перевірка кешу (Memoization check)
        if n in cache:
            return cache[n]

        # Крок 2: Рекурсивний розрахунок
        # Оскільки fibonacci(n-1) та fibonacci(n-2) самі є замиканнями,
        # вони також перевірять кеш перед обчисленням.
        result = fibonacci(n - 1) + fibonacci(n - 2)

        # Крок 3: Збереження результату в кеш (Cache update)
        cache[n] = result
        return result

    # 2. Повертаємо внутрішню функцію fibonacci, яка має доступ до cache
    return fibonacci



# Приклад використання
if __name__ == "__main__":

    # Створюємо екземпляр функції Фібоначчі з кешуванням
    fib = caching_fibonacci() 

    # Використовуємо функцію fibonacci для обчислення чисел Фібоначчі
    print(fib(10))  # Виведе 55
    print(fib(15))  # Виведе 610